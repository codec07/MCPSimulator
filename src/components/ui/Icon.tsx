/** Every icon name the registry can resolve, in declaration order. */
export const ICON_KEYS: readonly string[] = Object.freeze(Object.keys(REGISTRY));

/** Props accepted by {@link Icon}. */
export type IconProps = LucideProps & {
  /** Registry key; falls back to `Cpu` when unknown. */
  name: string;
  /** When set, the icon is exposed as an image with this accessible name. */
  title?: string;
};

/**
 * Render a registry icon by name.
 *
 * Defaults to `size = 16`, `strokeWidth = 1.75` and decorative
 * (`aria-hidden`) rendering; pass `title` to make it meaningful instead.
 */
export function Icon({
  name,
  size = 16,
  strokeWidth = 1.75,
  title,
  ...rest
}: IconProps): ReactElement {
  const Glyph = REGISTRY[name] ?? Cpu;

  if (title) {
    return (
      <Glyph
        size={size}
        strokeWidth={strokeWidth}
        role="img"
        aria-label={title}
        {...rest}
      >
        <title>{title}</title>
      </Glyph>
    );
  }

  return <Glyph size={size} strokeWidth={strokeWidth} aria-hidden {...rest} />;
}

/** Whether `name` resolves to a registered icon. */
export function hasIcon(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(REGISTRY, name);
}
