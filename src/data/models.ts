/**
 * Blended USD cost per 1M tokens, weighting input 35% and output 65%.
 * Rounded to 4 decimal places so the cheap specialist models stay readable.
 */
export function blendedPricePer1M(model: ModelDef): number {
  const blended = model.inputPricePer1M * 0.35 + model.outputPricePer1M * 0.65;
  return Math.round(blended * 10_000) / 10_000;
}

/** Letter grade for a model's quality index, S being the best. */
export function modelQualityTier(model: ModelDef): "S" | "A" | "B" | "C" | "D" {
  const q = model.quality;
  if (q >= 92) return "S";
  if (q >= 84) return "A";
  if (q >= 74) return "B";
  if (q >= 60) return "C";
  return "D";
}
